export function getListOfProvinces() {
  return VIETNAM_ADMINISTRATIVE_DATA.map(item => item.province);
}

export function getDistrictsOfProvince(provinceName) {
  const found = VIETNAM_ADMINISTRATIVE_DATA.find(item => item.province === provinceName);
  return found ? found.districts.map(d => d.district) : [];
}

export function getWardsOfDistrict(provinceName, districtName) {
  const found = VIETNAM_ADMINISTRATIVE_DATA.find(item => item.province === provinceName);
  if (!found) return [];
  const dist = found.districts.find(d => d.district === districtName);
  return dist ? dist.wards : [];
}
